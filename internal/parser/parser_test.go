func TestParseErrors(t *testing.T) {
	cases := []struct {
		name, in string
		want     error // sentinel, or nil when only a *ParseError is expected
	}{
		{"truncated", "*filter\n:INPUT ACCEPT [0:0]\n", ErrTruncated},
		{"bad counter", "*filter\n:INPUT ACCEPT [x:y]\nCOMMIT\n", nil},
		{"unknown chain", "*filter\n:INPUT ACCEPT [0:0]\n[0:0] -A NOPE -j ACCEPT\nCOMMIT\n", nil},
		{"unterminated quote", "*filter\n:INPUT ACCEPT [0:0]\n[0:0] -A INPUT -m comment --comment \"oops -j ACCEPT\nCOMMIT\n", nil},
		{"statement outside table", ":INPUT ACCEPT [0:0]\n", nil},
		{"commit without table", "COMMIT\n", nil},
		{"nested table", "*filter\n*nat\n", nil},
		{"uint64 overflow", "*filter\n:INPUT ACCEPT [99999999999999999999:0]\nCOMMIT\n", nil},
		{"rule without -A", "*filter\n:INPUT ACCEPT [0:0]\n[0:0] -I INPUT -j ACCEPT\nCOMMIT\n", nil},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			_, err := Parse(strings.NewReader(tc.in))
			if err == nil {
				t.Fatal("expected error")
			}
			if tc.want != nil && !errors.Is(err, tc.want) {
				t.Fatalf("err = %v, want %v", err, tc.want)
			}
			var pe *ParseError
			if tc.want == nil && !errors.As(err, &pe) {
				t.Fatalf("err = %T %v, want *ParseError", err, err)
			}
		})
	}
}

func TestParseLineTooLong(t *testing.T) {
	long := "*filter\n:INPUT ACCEPT [0:0]\n[0:0] -A INPUT -m comment --comment \"" +
		strings.Repeat("a", MaxLineBytes+10) + "\" -j ACCEPT\nCOMMIT\n"
	_, err := Parse(strings.NewReader(long))
	if err == nil {
		t.Fatal("expected error for oversize line")
	}
	if !errors.Is(err, bufio.ErrTooLong) {
		t.Fatalf("err = %v, want bufio.ErrTooLong in chain", err)
	}
}

func TestParseRejectsEmptyAndDuplicateNames(t *testing.T) {
	cases := []struct {
		name, in string
		line     int
	}{
		{"empty table", "*\n", 1},
		{"empty chain", "*filter\n:\n", 2},
		{"empty chain with policy", "*filter\n:INPUT ACCEPT [0:0]\n: ACCEPT\nCOMMIT\n", 3},
		{"duplicate chain", "*filter\n:INPUT ACCEPT [0:0]\n:FOO - [0:0]\n:INPUT ACCEPT [0:0]\nCOMMIT\n", 4},
		{"duplicate table", "*filter\n:INPUT ACCEPT [0:0]\nCOMMIT\n*filter\n", 4},
		{"invalid utf-8 table", "# c\n*fil\xfftr\n", 2},
		{"invalid utf-8 chain", "*filter\n:INPUT ACCEPT [0:0]\n:FO\xffO - [0:0]\nCOMMIT\n", 3},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			_, err := Parse(strings.NewReader(tc.in))
			var pe *ParseError
			if !errors.As(err, &pe) {
				t.Fatalf("err = %T %v, want *ParseError", err, err)
			}
			if pe.Line != tc.line {
				t.Errorf("line = %d, want %d (%v)", pe.Line, tc.line, err)
			}
		})
	}
}

func TestGoldenFixtures(t *testing.T) {
	cases := []struct {
		file          string
		tables        int
		chains, rules []int // per table, in order
	}{
		{"docker.save", 2, []int{5, 2}, []int{5, 1}},
		{"kube-proxy.save", 2, []int{7, 7}, []int{5, 4}},
		{"ufw.save", 1, []int{5}, []int{4}},
		{"fail2ban.save", 1, []int{4}, []int{3}},
		{"firewalld.save", 1, []int{4}, []int{5}},
		{"ipv6.save", 1, []int{3}, []int{1}},
		{"empty.save", 0, nil, nil},
	}
	for _, tc := range cases {
		t.Run(tc.file, func(t *testing.T) {
			tables := load(t, tc.file)
			if len(tables) != tc.tables {
				t.Fatalf("tables = %d, want %d", len(tables), tc.tables)
			}
			for i, tb := range tables {
				if len(tb.Chains) != tc.chains[i] {
					t.Errorf("table %s chains = %d, want %d", tb.Name, len(tb.Chains), tc.chains[i])
				}
				rules := 0
				for _, c := range tb.Chains {
					rules += len(c.Rules)
				}
				if rules != tc.rules[i] {
					t.Errorf("table %s rules = %d, want %d", tb.Name, rules, tc.rules[i])
				}
			}
		})
	}
}

func TestFixtureDetails(t *testing.T) {
	fw := load(t, "firewalld.save")[0]
	if got := chain(t, fw, "INPUT_ZONES").Rules[0].Target; got != "IN_public" {
		t.Errorf("-g target = %q", got)
	}
	f2b := load(t, "fail2ban.save")[0]
	if got := chain(t, f2b, "f2b-sshd").Rules[0].Target; got != "REJECT" {
		t.Errorf("REJECT target = %q", got)
	}
	ufw := load(t, "ufw.save")[0]
	if p := chain(t, ufw, "INPUT"); p.Policy != "DROP" || p.Packets != 3 {
		t.Errorf("ufw INPUT = %+v", p)
	}
}

func TestMalformedFixtures(t *testing.T) {
	for name, want := range map[string]error{"truncated.save": ErrTruncated, "bad-counter.save": nil, "unknown-chain.save": nil} {
		f, err := os.Open("../../testdata/" + name)
		if err != nil {
			t.Fatal(err)
		}
		_, perr := Parse(f)
		f.Close()
		if perr == nil {
			t.Errorf("%s: expected error", name)
		}
		if want != nil && !errors.Is(perr, want) {
			t.Errorf("%s: err = %v, want %v", name, perr, want)
		}
	}
}
