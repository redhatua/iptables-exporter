func load(t *testing.T, name string) []model.Table {
	t.Helper()
	f, err := os.Open("../../testdata/" + name)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	tables, err := Parse(f)
	if err != nil {
		t.Fatalf("Parse(%s): %v", name, err)
	}
	return tables
}

func chain(t *testing.T, tb model.Table, name string) *model.Chain {
	t.Helper()
	for _, c := range tb.Chains {
		if c.Name == name {
			return c
		}
	}
	t.Fatalf("chain %q not found in table %q", name, tb.Name)
	return nil
}

func TestParseDocker(t *testing.T) {
	tables := load(t, "docker.save")
	if len(tables) != 2 || tables[0].Name != "filter" || tables[1].Name != "nat" {
		t.Fatalf("tables = %+v", tables)
	}
	filter := tables[0]
	if len(filter.Chains) != 5 {
		t.Fatalf("filter chains = %d, want 5", len(filter.Chains))
	}
	fwd := chain(t, filter, "FORWARD")
	if fwd.Policy != "DROP" || fwd.Packets != 5 || fwd.Bytes != 420 || !fwd.Builtin() {
		t.Fatalf("FORWARD = %+v", fwd)
	}
	docker := chain(t, filter, "DOCKER")
	if docker.Policy != "-" || docker.Builtin() {
		t.Fatalf("DOCKER = %+v", docker)
	}
	in := chain(t, filter, "INPUT")
	if len(in.Rules) != 2 {
		t.Fatalf("INPUT rules = %d", len(in.Rules))
	}
	r := in.Rules[0]
	if r.Packets != 40 || r.Bytes != 3200 || r.Target != "ACCEPT" ||
		len(r.Comments) != 1 || r.Comments[0] != "iptx:id=ssh-in" {
		t.Fatalf("INPUT[0] = %+v", r)
	}
	if got := fwd.Rules[1].Comments; len(got) != 1 || got[0] != `allow "docker" out` {
		t.Fatalf("escaped comment = %q", got)
	}
	if got := fwd.Rules[0].Target; got != "DOCKER-USER" {
		t.Fatalf("jump target = %q", got)
	}
	nat := tables[1]
	if got := chain(t, nat, "POSTROUTING").Rules[0].Target; got != "MASQUERADE" {
		t.Fatalf("nat target = %q", got)
	}
}

